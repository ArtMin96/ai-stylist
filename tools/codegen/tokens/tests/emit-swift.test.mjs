// In-process tests for the Swift emitter (emit-swift.mjs) over the declaration tree
// (declarations.mjs): the three tier files, the reference scales, the colour roles and their five
// AppColors contexts, and one <Component>Tokens struct per component with one instance per context
// from resolveComponents. The repository DESIGN.md is emitted too, for the owner's naming
// decisions and the layout limits. Run by scripts/test/design-tokens.test.sh.
import assert from 'node:assert/strict';
import { test } from 'node:test';

import { emitSwift } from '../emit-swift.mjs';
import {
  REPO_DESIGN_MD,
  VALID,
  block,
  emitted,
  firstGroups,
  modelOf,
  modelOfEdited,
} from './models.mjs';

const files = emitted(emitSwift, modelOf(VALID));
const reference = files['ReferenceTokens.swift'];
const scheme = files['SchemeTokens.swift'];
const component = files['ComponentTokens.swift'];
const repo = emitted(emitSwift, modelOf(REPO_DESIGN_MD));
const CONTEXT_IDS = ['light', 'dark', 'brand', 'hcLight', 'hcDark'];

test('three tier files, each with the generated header, deterministic', () => {
  const names = ['ReferenceTokens.swift', 'SchemeTokens.swift', 'ComponentTokens.swift'];
  assert.deepEqual(Object.keys(files), names);
  for (const text of Object.values(files)) {
    assert.match(text, /^\/\/ GENERATED by tools\/codegen\/gen-tokens\.mjs\. DO NOT EDIT/);
    assert.match(text, /\n\/\/ Source: DESIGN\.md\n/);
    assert.ok(text.endsWith('}\n'), 'ends with one newline');
  }
  assert.deepEqual(emitted(emitSwift, modelOf(VALID)), files);
});

test('reference scales: numeric keys get the scale prefix, values are Double literals', () => {
  const spacing = [
    'nonisolated public enum AppSpacing {',
    '  public static let space4: Double = 4.0',
    '  public static let space8: Double = 8.0',
    '  public static let space16: Double = 16.0',
    '}',
  ];
  assert.equal(block(reference, 'nonisolated public enum AppSpacing'), spacing.join('\n'));
  assert.match(reference, /\n {2}public static let radius4: Double = 4\.0\n/);
  assert.match(reference, /\n {2}public static let full: Double = 999\.0\n/);
});

test('type styles: one AppTextStyle each, line height as a height, letter spacing in pt', () => {
  assert.match(reference, /\nnonisolated public struct AppTextStyle: Sendable, Equatable \{\n/);
  assert.match(reference, /\n {2}public let fontWeight: Int\n/);
  assert.match(reference, /\n {2}public let m3Roles: \[String\]\n/);
  const label = [
    '  public static let label = AppTextStyle(',
    '    fontFamily: "Fixture Sans",',
    '    fontSize: 12.0,',
    '    fontWeight: 600,',
    '    lineHeight: 16.0,',
    '    letterSpacing: 0.6,',
    '    dynamicType: "caption",',
    '    m3Roles: ["bodyMedium", "bodySmall", "labelLarge", "labelMedium", "labelSmall"]',
    '  )',
  ];
  assert.equal(block(reference, 'public static let label = AppTextStyle('), label.join('\n'));
  assert.match(reference, /\n {4}lineHeight: 13\.75,\n/);
  assert.match(reference, /\n {4}m3Roles: \[\]\n/);
});

test('elevation and motion: one-level groups become nested enums; curves are lists', () => {
  const sheet = [
    '  nonisolated public enum Sheet {',
    '    public static let offsetY: Double = -4.0',
    '    public static let blur: Double = 16.0',
    '    public static let color: AppColorRole = .scrim',
    '  }',
  ];
  assert.equal(block(reference, 'nonisolated public enum Sheet'), sheet.join('\n'));
  assert.match(reference, /\n {2}public static let raised: Double = 2\.0\n/);
  assert.match(reference, /\n {2}public static let screen: Double = 300\.0\n/);
  const easing = /\n {2}public static let easingEnter: \[Double\] = \[0\.2, 0\.0, 0\.0, 1\.0\]\n/;
  assert.match(reference, easing);
});

test('a literal shadow colour is ARGB; a motion alias is a reference', () => {
  const edited = modelOfEdited((fm) => {
    fm.elevation.sheet.color = 'rgba(27,27,25,0.14)';
    fm.motion.sheet = { duration: '250ms', easing: '{motion.easing-enter}' };
  });
  const text = emitted(emitSwift, edited)['ReferenceTokens.swift'];
  assert.match(text, /\n {4}public static let color: UInt32 = 0x241B_1B19\n/);
  assert.match(text, /\n {4}public static let easing: \[Double\] = AppMotion\.easingEnter\n/);
});

test('colour roles: one case per role in role order, fixed roles included', () => {
  const cases = firstGroups(scheme, /^ {2}case (\w+)$/gm);
  const roles = ['background', 'text', 'primary', 'primaryPressed', 'onPrimary', 'surface2'];
  assert.deepEqual(cases, [...roles, 'scrim', 'ringLight']);
  assert.match(scheme, /\nnonisolated public enum AppColorRole: CaseIterable, Sendable \{\n/);
});

test('AppColors: five contexts, ARGB with alpha, brand and high contrast fall back', () => {
  const instance = (name) => block(scheme, `public static let ${name} = AppColors(`);
  const instances = firstGroups(scheme, /^ {2}public static let (\w+) = AppColors\(/gm);
  assert.deepEqual(instances, CONTEXT_IDS);
  assert.match(instance('light'), /background: 0xFFFA_FAFA,/);
  assert.match(instance('light'), /scrim: 0x8000_0000,/);
  assert.match(instance('brand'), /background: 0xFF22_5533,/);
  assert.match(instance('brand'), /primary: 0xFF99_CCFF,/);
  assert.match(instance('hcLight'), /primary: 0xFF33_6699,/);
  assert.match(scheme, /\n {4}case \.ringLight: ringLight\n/);
  assert.match(scheme, /public subscript\(role: AppColorRole\) -> UInt32 \{/);
});

test('a component: properties then states as nested structs, one instance per context', () => {
  const tokens = block(component, 'nonisolated public struct ButtonPrimaryTokens');
  const fields = [...tokens.matchAll(/^ {2}public let (\w+): (\w+)$/gm)].map((m) => m.slice(1));
  const padding = ['paddingTop', 'paddingEnd', 'paddingBottom', 'paddingStart'];
  assert.deepEqual(fields, [
    ['backgroundColor', 'AppColorRole'],
    ['textColor', 'AppColorRole'],
    ['typography', 'AppTextStyle'],
    ['rounded', 'Double'],
    ['height', 'Double'],
    ...padding.map((side) => [side, 'Double']),
    ['pressed', 'Pressed'],
  ]);
  assert.match(tokens, /\n {2}nonisolated public struct Pressed: Sendable, Equatable \{\n/);
  const light = [
    '  public static let light = ButtonPrimaryTokens(',
    '    backgroundColor: .primary,',
    '    textColor: .onPrimary,',
    '    typography: AppTypography.label,',
    '    rounded: AppRadius.full,',
  ];
  assert.ok(tokens.includes(light.join('\n')), 'the light instance');
  assert.match(tokens, /\n {4}pressed: Pressed\(backgroundColor: \.primaryPressed\)\n {2}\)\n/);
  assert.deepEqual(firstGroups(tokens, /^ {2}public static let (\w+) = /gm), CONTEXT_IDS);
});

test('an unpaired component keeps its full key; a short instance stays on one line', () => {
  assert.match(component, /\nnonisolated public struct ChipOutlineLightTokens: Sendable/);
  const overlay = [
    '  public static let hcDark = OverlayTokens(',
    'backgroundColor: .scrim, gap: AppSpacing.space8, duration: AppMotion.press)',
  ];
  assert.ok(component.includes(`\n${overlay.join('')}\n`), 'one line');
});

test('a scheme-dependent value differs per context instance; high contrast its own width', () => {
  const edited = modelOfEdited((fm) => {
    fm.components['button-primary-pressed-dark'].backgroundColor = '{colors.primary-dark}';
    fm.components['button-primary-hc-light'] = {
      ...fm.components['button-primary-light'],
      backgroundColor: '{colors.background-hc-light}',
      textColor: '{colors.text-hc-light}',
      height: '56px',
    };
  });
  const text = emitted(emitSwift, edited)['ComponentTokens.swift'];
  const pressed = firstGroups(text, /pressed: Pressed\(backgroundColor: \.(\w+)\)/g);
  const expected = ['primaryPressed', 'primary', 'primary', 'primaryPressed', 'primary'];
  assert.deepEqual(pressed, expected);
  const heights = firstGroups(text, /^ {4}height: ([\d.]+),$/gm);
  assert.deepEqual(heights, ['48.0', '48.0', '48.0', '56.0', '48.0']);
});

test('an unpaired component has instances only for the contexts that draw from its scheme', () => {
  const instances = (text, type) => {
    const body = block(text, `nonisolated public struct ${type}`);
    return firstGroups(body, /^ {2}public static let (\w+) = /gm);
  };
  assert.deepEqual(instances(component, 'ChipOutlineLightTokens'), ['light', 'hcLight']);
  const banner = instances(repo['ComponentTokens.swift'], 'BannerDarkTokens');
  assert.deepEqual(banner, ['dark', 'brand', 'hcDark']);
});

test('every generated type is nonisolated (the package defaults to MainActor isolation)', () => {
  for (const text of [...Object.values(files), ...Object.values(repo)]) {
    for (const line of text.split('\n').filter((l) => /\b(enum|struct) \w/.test(l))) {
      assert.match(line, /^ *nonisolated public (enum|struct) /, line);
    }
  }
});

test('the repository DESIGN.md: owner naming decisions of 2026-10-20', () => {
  const text = repo['ComponentTokens.swift'];
  const types = new Set(firstGroups(text, /^nonisolated public struct (\w+)/gm));
  for (const name of ['BannerDarkTokens', 'CameraModeSwitchTokens', 'CameraModeSelectedTokens']) {
    assert.ok(types.has(name), `${name} is emitted`);
  }
  for (const name of ['BannerTokens', 'CameraModeTokens']) {
    assert.ok(!types.has(name), `${name} is not emitted`);
  }
  assert.ok(types.has('ButtonActionSelectedTokens'), 'no state inferred without a base key');
  assert.match(repo['ReferenceTokens.swift'], /\n {2}nonisolated public enum SheetLight \{\n/);
});

test('layout: no line over 120 columns, no tab, no trailing space, 2-space indents', () => {
  for (const [file, text] of [...Object.entries(files), ...Object.entries(repo)]) {
    text.split('\n').forEach((line, i) => {
      const at = `${file}:${i + 1}`;
      assert.ok(line.length <= 120, `${at} is ${line.length} columns`);
      assert.ok(!/\t| $/.test(line), `${at} has a tab or a trailing space`);
      assert.equal(/^ */.exec(line)[0].length % 2, 0, `${at} indent`);
    });
  }
});
