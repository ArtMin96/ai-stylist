// Writes the plugin that `just skills-eval` hands to `claude plugin eval` for one skill and mode:
// copies of the skills under test (never the sources under .agents/skills), the cases from
// cases.mjs and, for `tasks`, the snapshot of the repository that every run starts from. Node
// built-ins, git, bash and tar.
import { execFileSync, spawnSync } from 'node:child_process';
import {
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';

import {
  RefusalError,
  scaffoldScript,
  skillStepText,
  systemPromptFor,
  taskCase,
  triggerCase,
} from './cases.mjs';

const SKILLS_DIR = '.agents/skills';
const EVAL_FILES = { tasks: 'evals.json', triggers: 'trigger-evals.json' };
/**
 * The skill layer: a run gets a skill through the plugin only, so no directory of these names is
 * in its workspace, at any depth. planning/.agents/skills holds older copies of some skills.
 */
const SNAPSHOT_EXCLUDED = ['.agents', '.claude'];
/** The runner kills a scaffold script after 120 s; a slower one than this is refused up front. */
const SCAFFOLD_BUDGET_SECONDS = 30;
const MANIFEST = {
  name: 'skills-eval',
  version: '0.0.0',
  description: 'Generated by `just skills-eval` from .agents/skills. Not for distribution.',
};

function git(root, args) {
  return execFileSync('git', ['-C', root, ...args], { encoding: 'utf8' });
}

/** The commit a run is built from. */
export const headSha = (root) => git(root, ['rev-parse', 'HEAD']).trim();

/**
 * The skill files and CLAUDE.md that differ from HEAD, as `git status --porcelain` lines. A run
 * reads them from the working tree, so the commit alone does not identify what it measured.
 */
export function uncommittedSources(root) {
  const status = git(root, ['status', '--porcelain', '--', SKILLS_DIR, 'CLAUDE.md']);
  return status.split('\n').filter((line) => line !== '');
}

/** The skills under .agents/skills, sorted by name. */
export function listSkills(root) {
  const entries = readdirSync(path.join(root, SKILLS_DIR), { withFileTypes: true });
  const names = entries.filter((entry) => entry.isDirectory()).map((entry) => entry.name);
  const hasSkillFile = (name) => existsSync(path.join(root, SKILLS_DIR, name, 'SKILL.md'));
  return names.filter(hasSkillFile).sort();
}

/** Step 3 of "Session workflow" from the root CLAUDE.md; refused when it is not there. */
export function readSkillStep(root) {
  return skillStepText(readFileSync(path.join(root, 'CLAUDE.md'), 'utf8'));
}

/**
 * The tasks (`tasks`) or queries (`triggers`) of one skill, as its eval file lists them. A
 * missing, malformed or empty file is refused by its repository path.
 */
export function evalEntries(root, skill, mode) {
  const shown = `${SKILLS_DIR}/${skill}/evals/${EVAL_FILES[mode]}`;
  const file = path.join(root, shown);
  if (!existsSync(file)) throw new RefusalError(`${shown} does not exist`);
  let parsed;
  try {
    parsed = JSON.parse(readFileSync(file, 'utf8'));
  } catch (error) {
    throw new RefusalError(`${shown} is not valid JSON: ${error.message}`, { cause: error });
  }
  const entries = mode === 'tasks' ? parsed?.evals : parsed;
  if (!Array.isArray(entries) || entries.length === 0) {
    throw new RefusalError(`${shown} lists nothing to run`);
  }
  return entries;
}

/** Copies one skill without its evals/ and points the copy's own repo paths at the copy. */
function copySkill(root, skill, target) {
  const source = path.join(root, SKILLS_DIR, skill);
  const evals = path.join(source, 'evals');
  cpSync(source, target, { recursive: true, filter: (from) => from !== evals });
  // `.agents/skills/<skill>/` does not exist in a run's workspace. Left as is, the first read of a
  // reference fails and some runs never find the file (2 of 12 in the 2026-10-12 pilot).
  const ownPath = `${SKILLS_DIR}/${skill}/`;
  for (const entry of readdirSync(target, { recursive: true, withFileTypes: true })) {
    if (!entry.isFile()) continue;
    const file = path.join(entry.parentPath, entry.name);
    const text = readFileSync(file, 'utf8');
    if (text.includes(ownPath)) writeFileSync(file, text.replaceAll(ownPath, `${target}/`));
  }
}

function writeCases(pluginDir, cases) {
  for (const { name, files } of cases) {
    for (const [relative, text] of Object.entries(files)) {
      const file = path.join(pluginDir, 'evals', name, relative);
      mkdirSync(path.dirname(file), { recursive: true });
      writeFileSync(file, text);
    }
  }
}

/**
 * Builds the plugin of one skill and mode in `pluginDir` and returns its case names. `skills` is
 * every skill (a `triggers` plugin holds them all), `skillStep` is readSkillStep(), and
 * `snapshotFile` is where the `tasks` scaffold will find the snapshot. Every input is read and
 * checked before the first file is written, so a refused unit leaves nothing behind.
 */
export function generatePlugin({ root, skill, mode, skills, skillStep, pluginDir, snapshotFile }) {
  const entries = evalEntries(root, skill, mode);
  const systemPrompt = systemPromptFor(mode, skillStep);
  const tasks = mode === 'tasks';
  const skillDir = path.join(pluginDir, 'skills', skill);
  const scaffold = scaffoldScript(snapshotFile);
  const cases = entries.map((entry, i) => {
    if (tasks) return taskCase({ skill, task: entry, skillDir, systemPrompt, scaffold });
    return triggerCase({ skill, index: i + 1, entry, systemPrompt });
  });
  const names = cases.map((entry) => entry.name);
  // A repeated name would let one case directory silently replace another.
  const repeated = names.find((name, i) => names.indexOf(name) !== i);
  if (repeated !== undefined) {
    throw new RefusalError(`two cases would be named ${repeated}: task ids must be unique`);
  }

  mkdirSync(path.join(pluginDir, '.claude-plugin'), { recursive: true });
  const manifest = path.join(pluginDir, '.claude-plugin', 'plugin.json');
  writeFileSync(manifest, `${JSON.stringify(MANIFEST, null, 2)}\n`);
  for (const name of tasks ? [skill] : skills) {
    copySkill(root, name, path.join(pluginDir, 'skills', name));
  }
  writeCases(pluginDir, cases);
  return names;
}

/** Writes a tar of the tracked files at HEAD without the skill layer; returns its size in bytes. */
export function writeSnapshot(root, file) {
  const excluded = SNAPSHOT_EXCLUDED.map((name) => `:(exclude,glob)**/${name}/**`);
  git(root, ['archive', '--format=tar', '-o', file, 'HEAD', '--', '.', ...excluded]);
  return statSync(file).size;
}

/**
 * Runs a scaffold script the way the runner does, in an empty directory with only PATH, HOME and
 * TMPDIR set, then discards what it wrote. Returns the seconds it took and the number of entries
 * it left; throws a RefusalError when it fails or runs over the budget.
 */
export function tryScaffold(script) {
  const scratch = mkdtempSync(path.join(tmpdir(), 'skills-eval-scaffold-'));
  try {
    const workspace = path.join(scratch, 'workspace');
    mkdirSync(workspace);
    const env = { PATH: process.env.PATH ?? '', HOME: scratch, TMPDIR: scratch };
    const timeout = SCAFFOLD_BUDGET_SECONDS * 1000;
    const started = performance.now();
    const run = spawnSync('bash', [script], { cwd: workspace, env, encoding: 'utf8', timeout });
    const seconds = Number(((performance.now() - started) / 1000).toFixed(2));
    if (run.status !== 0) {
      const detail = run.error?.message ?? (run.stderr.trim() || `exit ${run.status}`);
      const limit = `${SCAFFOLD_BUDGET_SECONDS} s`;
      throw new RefusalError(`the scaffold script failed or ran over ${limit}: ${detail}`);
    }
    return { seconds, entries: readdirSync(workspace, { recursive: true }).length };
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}
