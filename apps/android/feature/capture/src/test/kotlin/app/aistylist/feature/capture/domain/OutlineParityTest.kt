/**
 * The shared parity fixture `tools/capture-frames/parity/outline-parity.json` (generated by
 * `outline_reference.py`; iOS tests the same file): every contour, IoU and temporal case within the
 * fixture's tolerance, and every spec number equal to the fixture's `params`.
 */
class OutlineParityTest {
    private val fixture: JsonObject = loadParityFixture()

    private val tolerance = fixture.number("tolerance")

    @Test
    fun `the spec numbers equal the fixture params`() {
        val params = fixture.getValue("params").jsonObject
        assertEquals(CaptureRules.Ios.MASK_INTERVAL_MS, params.int("maskIntervalMs"))
        assertEquals(OutlineSpec.CROP_GROW_DIVISOR, params.int("cropGrowDivisor"))
        assertEquals(OutlineSpec.CROP_GROW_MIN_PX, params.int("cropGrowMinPx"))
        assertEquals(OutlineSpec.LONG_SIDE_PX, params.int("longSidePx"))
        assertEquals(OutlineSpec.FOREGROUND_AT_LEAST, params.number("foregroundAtLeast"), 0.0)
        assertEquals(OutlineSpec.EPSILON_PX, params.number("epsilonPx"), 0.0)
        assertEquals(OutlineSpec.POINT_COUNT, params.int("pointCount"))
        assertEquals(OutlineSpec.KEEP_AT_LEAST_IOU, params.number("keepAtLeastIou"), 0.0)
        assertEquals(OutlineSpec.SWITCH_AT_AREA_RATIO, params.number("switchAtAreaRatio"), 0.0)
        assertEquals(OutlineSpec.SNAP_BELOW_IOU, params.number("snapBelowIou"), 0.0)
        assertEquals(OutlineSpec.EMA_ALPHA, params.number("emaAlpha"), 0.0)
        assertEquals(OutlineSpec.CLEAR_AFTER_MISSED_UPDATES, params.int("clearAfterMissedUpdates"))
        assertEquals(OutlineSpec.IOU_GRID_CELLS, params.int("iouGridCells"))
        assertEquals(0.005, tolerance, 0.0)
    }

    @Test
    fun `every contour case matches the reference`() {
        val cases = fixture.getValue("contour").jsonArray
        assertTrue("the fixture has contour cases", cases.isNotEmpty())
        cases.forEach { element ->
            val case = element.jsonObject
            val name = case.string("name")
            val width = case.int("width")
            val height = case.int("height")
            val mask = case.mask()

            val trace = traceOutline(width, height, mask)

            val expected = case.getValue("expected")
            if (expected is JsonNull) {
                assertNull(name, trace)
            } else {
                val traced = requireNotNull(trace) { "$name: no outline" }
                assertEquals("$name vertex count", case.int("simplifiedVertexCount"), traced.simplifiedVertexCount)
                assertClose(name, expected.points(), traced.points)
            }
        }
    }

    @Test
    fun `every IoU case matches the reference`() {
        fixture.getValue("iou").jsonArray.forEach { element ->
            val case = element.jsonObject
            val iou = polygonIou(case.getValue("a").points(), case.getValue("b").points())
            assertEquals(case.string("name"), case.number("expected"), iou, 1e-6)
        }
    }

    @Test
    fun `every temporal case matches the reference`() {
        fixture.getValue("temporal").jsonArray.forEach { element ->
            val case = element.jsonObject
            var tracker = OutlineTracker()
            case.getValue("steps").jsonArray.forEachIndexed { index, step ->
                val candidates =
                    step.jsonObject.getValue("candidates").jsonArray.map {
                        OutlineCandidate(it.jsonObject.number("areaShare"), it.jsonObject.getValue("points").points())
                    }
                tracker = tracker.update(candidates)
                val label = "${case.string("name")} step $index"
                val expected = step.jsonObject.getValue("expected")
                if (expected is JsonNull) {
                    assertNull(label, tracker.drawn)
                } else {
                    assertClose(label, expected.points(), requireNotNull(tracker.drawn) { label })
                }
            }
        }
    }

    @Test
    fun `round half to even matches the reference rounding`() {
        assertEquals(2L, roundHalfEven(5, 2))
        assertEquals(4L, roundHalfEven(7, 2))
        assertEquals(1L, roundHalfEven(3, 4))
        assertEquals(0L, roundHalfEven(1, 4))
        assertEquals(2L, roundHalfEven(10, 4))
        assertEquals(4L, roundHalfEven(14, 4))
    }

    private fun assertClose(
        label: String,
        expected: List<NormalizedPoint>,
        actual: List<NormalizedPoint>,
    ) {
        assertEquals("$label point count", expected.size, actual.size)
        expected.zip(actual).forEachIndexed { i, (e, a) ->
            assertTrue(
                "$label point $i: expected (${e.x}, ${e.y}), got (${a.x}, ${a.y})",
                abs(e.x - a.x) <= tolerance && abs(e.y - a.y) <= tolerance,
            )
        }
    }
}

/** The shared parity fixture, a test resource (see this module's build file). */
internal fun loadParityFixture(): JsonObject =
    Json
        .parseToJsonElement(
            requireNotNull(OutlineParityTest::class.java.classLoader?.getResource("outline-parity.json")) {
                "parity fixture missing"
            }.readText(),
        ).jsonObject

/** A contour case's mask (`#` is foreground), row-major. */
internal fun JsonObject.mask(): BooleanArray {
    val width = int("width")
    val rows = getValue("rows").jsonArray.map { it.jsonPrimitive.content }
    return BooleanArray(width * int("height")) { rows[it / width][it % width] == '#' }
}

internal fun JsonObject.number(key: String): Double = getValue(key).jsonPrimitive.double

internal fun JsonObject.int(key: String): Int = getValue(key).jsonPrimitive.int

internal fun JsonObject.string(key: String): String = getValue(key).jsonPrimitive.content

internal fun JsonElement.points(): List<NormalizedPoint> =
    (this as JsonArray).map { pair ->
        val xy = pair.jsonArray
        NormalizedPoint(xy[0].jsonPrimitive.double, xy[1].jsonPrimitive.double)
    }
