// Declaration tree -> Kotlin for `:core:designsystem` (DEC-87:
// apps/android/core/designsystem/src/main/kotlin/app/aistylist/core/designsystem/generated/).
// Plain values only (Double, Int, String, Long ARGB), so the pure-JVM module needs no dependency;
// the Compose theme maps them to Color, Dp and TextStyle. Layout follows ktlint_official
// (apps/android/.editorconfig): 4-space indent, 120 columns, trailing commas, a multiline value
// wrapped after its `=` (multiline-expression-wrapping), no empty class body.
import { docText, ktEnumEntry, ktIdent, ktStr, nestedTypeName, num } from './naming.mjs';
import { inline, joinMembers, renderDeclaration, renderTiers, valueLines } from './render.mjs';

const INDENT = '    ';
const PACKAGE = 'app.aistylist.core.designsystem.generated';
const TYPE = {
  double: 'Double',
  int: 'Int',
  bool: 'Boolean',
  string: 'String',
  color: 'Long',
  role: 'AppColorRole',
  textStyle: 'AppTextStyle',
  stringList: 'List<String>',
  doubleList: 'List<Double>',
};
/** `role?` -> `AppColorRole?`, `list:ButtonLook` -> `List<ButtonLook>`, a class name as is. */
const typeName = (type) => {
  if (type.endsWith('?')) return `${typeName(type.slice(0, -1))}?`;
  if (type.startsWith('list:')) return `List<${typeName(type.slice('list:'.length))}>`;
  return TYPE[type] ?? type;
};

export const kotlin = {
  extension: 'kt',
  indent: INDENT,
  limit: 120,
  wrapAfterAssign: true,
  callTrailingComma: true,
  // ktlint_official trailing-comma-on-call-site: every wrapped argument list ends with one.
  list: { open: 'listOf(', close: ')', empty: 'emptyList()', singleItemTrailingComma: true },
  argLabel: (name) => `${ktIdent(name)} = `,
  spell: {
    double: num,
    string: ktStr,
    role: (id) => `AppColorRole.${ktEnumEntry(id)}`,
    ref: (namespace, member) => `${namespace}.${ktIdent(member)}`,
    enumCase: (type, id) => `${type}.${ktEnumEntry(id)}`,
    unionCase: (type, name) => `${type}.${nestedTypeName(name)}`,
    none: 'null',
  },
  header: (source, title) => [
    '// GENERATED by tools/codegen/gen-tokens.mjs. DO NOT EDIT: run `just generate`.',
    `// Source: ${source}`,
    `// ${title} (DEC-87).`,
    `package ${PACKAGE}`,
  ],
  doc: (text, pad) => `${pad}/** ${docText(text)} */`,
  namespaceHead: (name, access) => (access ? `${access} object ${name}` : `object ${name}`),
  emptyNamespace: (name) => `object ${name}`,
  constant(member, depth) {
    const pad = INDENT.repeat(depth);
    const head = `${pad}val ${ktIdent(member.name)}: ${typeName(member.type)} = `;
    return valueLines(kotlin, head, member, pad);
  },
  struct(decl, depth) {
    const pad = INDENT.repeat(depth);
    const inner = pad + INDENT;
    const parameters = decl.fields.map(
      (f) => `${inner}val ${ktIdent(f.name)}: ${typeName(f.type)},`,
    );
    const lookup = decl.lookup ? [lookupLines(decl, inner)] : [];
    const find = decl.find ? [findLines(decl.find, inner)] : [];
    const nested = decl.nested.map((n) => renderDeclaration(kotlin, n, depth + 1));
    const companion = decl.instances.length > 0 ? [companionLines(decl, inner)] : [];
    const body = [...lookup, ...find, ...nested, ...companion];
    return [
      ...(decl.doc ? [kotlin.doc(decl.doc, pad)] : []),
      `${pad}data class ${decl.name}(`,
      ...parameters,
      ...(body.length > 0 ? [`${pad}) {`, ...joinMembers(body), `${pad}}`] : [`${pad})`]),
    ];
  },
  roles: (decl) => [
    `/** ${docText(decl.doc)} */`,
    `enum class ${decl.name}(`,
    `${INDENT}val id: String,`,
    `${INDENT}internal val read: (${decl.valuesType}) -> Long,`,
    ') {',
    ...decl.cases.map(({ name, id }) => {
      const read = `${decl.valuesType}::${ktIdent(name)}`;
      return `${INDENT}${ktEnumEntry(name)}(${ktStr(id)}, ${read}),`;
    }),
    '}',
  ],
  /**
   * A closed set of kebab ids: the entry is the Kotlin name, `id` the id, then each extra field
   * (`decl.fields`, typed; each case's `values`). An entry longer than the limit takes one argument
   * per line (ktlint argument-list-wrapping, with its trailing comma).
   */
  enum(decl) {
    const fields = [{ name: 'id', type: 'string' }, ...(decl.fields ?? [])];
    return [
      `/** ${docText(decl.doc)} */`,
      `enum class ${decl.name}(`,
      ...fields.map(({ name, type }) => `${INDENT}val ${ktIdent(name)}: ${typeName(type)},`),
      ') {',
      ...decl.cases.flatMap((c) => {
        const values = { ...c.values, id: { t: 'string', s: c.id } };
        const args = fields.map(({ name, type }) => inline(kotlin, values[name], type));
        const entry = `${INDENT}${ktEnumEntry(c.name)}(`;
        const single = `${entry}${args.join(', ')}),`;
        if (single.length <= kotlin.limit) return [single];
        return [entry, ...args.map((arg) => `${INDENT}${INDENT}${arg},`), `${INDENT}),`];
      }),
      '}',
    ];
  },
  /**
   * A closed set of cases, some with a payload: a sealed interface whose cases are a data class
   * (`Glyph(val name: AppIconName)`) or a data object (`Prop`).
   */
  union(decl) {
    const cases = decl.cases.map(({ name, doc, fields }) => {
      const type = nestedTypeName(name);
      const head = [`${INDENT}/** ${docText(doc)} */`];
      if (fields.length === 0) return [...head, `${INDENT}data object ${type} : ${decl.name}`];
      return [
        ...head,
        `${INDENT}data class ${type}(`,
        ...fields.map((f) => `${INDENT}${INDENT}val ${ktIdent(f.name)}: ${typeName(f.type)},`),
        `${INDENT}) : ${decl.name}`,
      ];
    });
    return [
      `/** ${docText(decl.doc)} */`,
      `sealed interface ${decl.name} {`,
      ...joinMembers(cases),
      '}',
    ];
  },
};

/** `appearance(variant, size, state)`: the matching list item's result, or null when none does. */
function findLines(find, pad) {
  const params = find.keys.map(({ name, type }) => `${ktIdent(name)}: ${typeName(type)}`);
  const head = `${pad}fun ${find.name}(`;
  const tail = `): ${typeName(find.resultType)}? =`;
  const single = `${head}${params.join(', ')}${tail}`;
  const wrapped = params.map((p) => `${pad}${INDENT}${p},`);
  // ktlint_official forces one parameter per line from two parameters on, whatever the length.
  const fits = single.length <= kotlin.limit && params.length < 2;
  const signature = fits ? [single] : [head, ...wrapped, `${pad}${tail}`];
  const match = find.keys.map(({ name }) => `it.${name} == ${ktIdent(name)}`).join(' && ');
  const body = `${find.list}.firstOrNull { ${match} }?.${find.result}`;
  // ktlint_official keeps an expression body on the signature's last line when the joined line fits.
  const joined = `${signature.at(-1)} ${body}`;
  const lines =
    joined.length <= kotlin.limit
      ? [...signature.slice(0, -1), joined]
      : [...signature, `${pad}${INDENT}${body}`];
  return [`${pad}/** ${docText(find.doc)} */`, ...lines];
}

/** `colors[role]`: each role entry reads its own property, so no `when` over every role. */
const lookupLines = (decl, pad) => {
  const { roleType, valueType } = decl.lookup;
  return [
    `${pad}/** The value of [role] in this context. */`,
    `${pad}operator fun get(role: ${roleType}): ${typeName(valueType)} = role.read(this)`,
  ];
};

/** One instance per context, in the companion object (`AppColors.light`, `ChipTokens.dark`). */
function companionLines(decl, pad) {
  const inner = pad + INDENT;
  const instances = decl.instances.map(({ name, value }) =>
    valueLines(kotlin, `${inner}val ${ktIdent(name)}: ${decl.name} = `, { value }, inner),
  );
  return [`${pad}companion object {`, ...joinMembers(instances), `${pad}}`];
}

/** `{ ReferenceTokens.kt, SchemeTokens.kt, ComponentTokens.kt }`. */
export const emitKotlin = (tiers, source) => renderTiers(kotlin, tiers, source);
