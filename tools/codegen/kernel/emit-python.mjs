// shared-kernel registries -> Python constants (workers/ml/generated/ai_stylist_generated/kernel/).
// The registries the workers mirror: forbidden-log-keys (+ its word-split examples), log-redaction
// and correlation (with the envelope's `correlationId` rule, read by gen-kernel.mjs from
// packages/contracts). The worker imports these instead of keeping a hand copy pinned by a test, so
// a worker image (which holds no `packages/`) carries the registry values. gen-python.sh calls
// `gen-kernel.mjs python` into its staging dir and formats the result with the workspace ruff config.
import { src } from './naming.mjs';

const ENVELOPE_CORRELATION_ID = 'packages/contracts/events/envelope.json#/properties/correlationId';

const banner = (names, extraSources = []) =>
  [
    '# GENERATED by tools/codegen/gen-kernel.mjs. DO NOT EDIT: edit the registry and run `just generate`.',
    ...names.map((n) => `# Source: ${src(n)}`),
    ...extraSources.map((s) => `# Source: ${s}`),
  ].join('\n');

const hex = (cp, width) => cp.toString(16).padStart(width, '0');

/**
 * A Python str literal in ASCII. JSON string syntax is valid Python for every string (escapes `\`,
 * `"`, control characters and lone surrogates); every other non-ASCII code point becomes a `\u` or
 * `\U` escape, so values with newlines, accents or look-alike characters are written exactly and
 * no confusable character reaches the source (ruff RUF001).
 */
const pyStr = (s) =>
  // eslint-disable-next-line no-control-regex
  JSON.stringify(s).replace(/[^\x00-\x7e]/gu, (ch) => {
    const cp = ch.codePointAt(0);
    return cp > 0xffff ? `\\U${hex(cp, 8)}` : `\\u${hex(cp, 4)}`;
  });

/** A regex source as a raw string when that is exact, else a plain literal (same value). */
const pyRegex = (s) =>
  // eslint-disable-next-line no-control-regex
  /["\u0000-\u001f\u007f]|\\$/.test(s) ? pyStr(s) : `r"${s}"`;

const pyTuple = (items) => ['(', ...items.map((v) => `    ${pyStr(v)},`), ')'].join('\n');

const pyFrozenset = (items) =>
  ['frozenset(', '    {', ...items.map((v) => `        ${pyStr(v)},`), '    }', ')'].join('\n');

const pyInt = (n) => {
  if (!Number.isInteger(n)) throw new Error(`expected an integer, got ${JSON.stringify(n)}`);
  return String(n);
};

export function emitPython(reg, contracts) {
  const keys = reg['forbidden-log-keys'];
  const examples = reg['forbidden-log-keys.examples'];
  const lr = reg['log-redaction'];
  const corr = reg.correlation;
  const idRule = contracts.correlationId;
  const out = {};

  out['forbidden_log_keys.py'] = [
    banner(['forbidden-log-keys', 'forbidden-log-keys.examples']),
    '"""Forbidden log key words (planning/11 §8) and their word-split examples.',
    '',
    'A log key is forbidden when the whole key, or any of its camelCase, snake_case or kebab-case',
    'words, lowercased, is in `FORBIDDEN_LOG_KEYS`. Every `FORBIDDEN_LOG_KEY_EXAMPLES_FORBIDDEN` key',
    'must match and no `FORBIDDEN_LOG_KEY_EXAMPLES_ALLOWED` key may.',
    '"""',
    '',
    'from typing import Final',
    '',
    `FORBIDDEN_LOG_KEYS: Final[frozenset[str]] = ${pyFrozenset(keys.keys)}`,
    '',
    `FORBIDDEN_LOG_KEY_EXAMPLES_FORBIDDEN: Final[tuple[str, ...]] = ${pyTuple(examples.forbidden)}`,
    '',
    `FORBIDDEN_LOG_KEY_EXAMPLES_ALLOWED: Final[tuple[str, ...]] = ${pyTuple(examples.allowed)}`,
    '',
  ].join('\n');

  const { exceptionType, nestContext } = lr.vectors;
  out['log_redaction.py'] = [
    banner(['log-redaction']),
    '"""Error-shape rules for logs and spans (planning/11 §8, planning/14 §2-3).',
    '',
    'Each shape is the registry source verbatim, compiled with `re.ASCII` (`\\\\w` is `[A-Za-z0-9_]`,',
    'as in JavaScript). Always match with `fullmatch`, so `$` never accepts a trailing newline.',
    'The vectors are the labelled test values every implementation is tested against.',
    '"""',
    '',
    'import re',
    'from typing import Final',
    '',
    '# An error class name kept in a log `err.type` or a span `exception.type`, else `Error`.',
    `ERROR_NAME_SHAPE: Final[re.Pattern[str]] = re.compile(${pyRegex(lr.errorNameShape)}, re.ASCII)`,
    '# An error code kept in a log `err.code` or a span `exception.type` (SQLSTATE, system code).',
    `CODE_SHAPE: Final[re.Pattern[str]] = re.compile(${pyRegex(lr.codeShape)}, re.ASCII)`,
    '# Cause links of a logged error that are followed; the bound also ends a circular chain.',
    `MAX_CAUSE_DEPTH: Final[int] = ${pyInt(lr.maxCauseDepth)}`,
    '# A Nest logger `context` kept as written (a PascalCase class name), else redacted.',
    `NEST_CONTEXT_SHAPE: Final[re.Pattern[str]] = re.compile(${pyRegex(lr.nestContextShape)}, re.ASCII)`,
    '',
    '# A span `exception.type` is kept when it matches ERROR_NAME_SHAPE or CODE_SHAPE, else replaced.',
    `EXCEPTION_TYPE_KEPT: Final[tuple[str, ...]] = ${pyTuple(exceptionType.kept)}`,
    '',
    `EXCEPTION_TYPE_REPLACED: Final[tuple[str, ...]] = ${pyTuple(exceptionType.replaced)}`,
    '',
    '# A Nest logger `context` is kept when it matches NEST_CONTEXT_SHAPE, else redacted.',
    `NEST_CONTEXT_KEPT: Final[tuple[str, ...]] = ${pyTuple(nestContext.kept)}`,
    '',
    `NEST_CONTEXT_REDACTED: Final[tuple[str, ...]] = ${pyTuple(nestContext.redacted)}`,
    '',
  ].join('\n');

  out['correlation.py'] = [
    banner(['correlation'], [ENVELOPE_CORRELATION_ID]),
    '"""Correlation id propagation (planning/14 §2): the header and log key every hop carries the id',
    "under, and the event envelope's `correlationId` rule for which ids are valid.",
    '',
    'An id is valid when its length is within CORRELATION_ID_MIN_LENGTH..CORRELATION_ID_MAX_LENGTH',
    "and CORRELATION_ID_PATTERN (the schema's `pattern` verbatim, compiled with `re.ASCII` as JSON",
    "Schema's ECMA-262 regex reads it) matches the whole id with `fullmatch`. The vectors are the",
    'labelled ids every check of the rule is tested against.',
    '"""',
    '',
    'import re',
    'from typing import Final',
    '',
    '# Request and response header that carries the id (lowercase).',
    `CORRELATION_ID_HEADER: Final[str] = ${pyStr(corr.header)}`,
    '# Log key and span attribute name.',
    `CORRELATION_ID_KEY: Final[str] = ${pyStr(corr.logKey)}`,
    "# The envelope schema's `correlationId` bounds, in characters.",
    `CORRELATION_ID_MIN_LENGTH: Final[int] = ${pyInt(idRule.minLength)}`,
    `CORRELATION_ID_MAX_LENGTH: Final[int] = ${pyInt(idRule.maxLength)}`,
    "# The envelope schema's `correlationId` pattern; always match with `fullmatch`.",
    `CORRELATION_ID_PATTERN: Final[re.Pattern[str]] = re.compile(${pyRegex(idRule.pattern)}, re.ASCII)`,
    '',
    '# Ids every check MUST accept.',
    `CORRELATION_ID_ACCEPTED: Final[tuple[str, ...]] = ${pyTuple(corr.vectors.accepted)}`,
    '',
    '# Ids every check MUST reject.',
    `CORRELATION_ID_REJECTED: Final[tuple[str, ...]] = ${pyTuple(corr.vectors.rejected)}`,
    '',
  ].join('\n');

  const exportsByModule = {
    correlation: [
      'CORRELATION_ID_ACCEPTED',
      'CORRELATION_ID_HEADER',
      'CORRELATION_ID_KEY',
      'CORRELATION_ID_MAX_LENGTH',
      'CORRELATION_ID_MIN_LENGTH',
      'CORRELATION_ID_PATTERN',
      'CORRELATION_ID_REJECTED',
    ],
    forbidden_log_keys: [
      'FORBIDDEN_LOG_KEYS',
      'FORBIDDEN_LOG_KEY_EXAMPLES_ALLOWED',
      'FORBIDDEN_LOG_KEY_EXAMPLES_FORBIDDEN',
    ],
    log_redaction: [
      'CODE_SHAPE',
      'ERROR_NAME_SHAPE',
      'EXCEPTION_TYPE_KEPT',
      'EXCEPTION_TYPE_REPLACED',
      'MAX_CAUSE_DEPTH',
      'NEST_CONTEXT_KEPT',
      'NEST_CONTEXT_REDACTED',
      'NEST_CONTEXT_SHAPE',
    ],
  };
  const all = Object.values(exportsByModule).flat().sort();
  out['__init__.py'] = [
    banner(
      ['forbidden-log-keys', 'forbidden-log-keys.examples', 'log-redaction', 'correlation'],
      [ENVELOPE_CORRELATION_ID],
    ),
    '"""shared-kernel registries the workers read (packages/shared-kernel/registry, DEC-55)."""',
    '',
    ...Object.entries(exportsByModule).map(
      ([mod, names]) =>
        `from ai_stylist_generated.kernel.${mod} import (\n${names.map((n) => `    ${n},`).join('\n')}\n)`,
    ),
    '',
    `__all__ = [\n${all.map((n) => `    ${pyStr(n)},`).join('\n')}\n]`,
    '',
  ].join('\n');
  return out;
}
