// shared-kernel registries -> Swift (target AIStylistKernel in packages/contracts/gen/swift-client).
// Every type is a String-backed enum (CaseIterable, Sendable) or a namespace enum of static lets,
// so the module compiles under Swift 6 strict concurrency with no dependencies.
import {
  assertUniqueIds,
  camel,
  captureHintKinds,
  docText,
  int,
  integerKeys,
  isNumberBlock,
  num,
  pascal,
  src,
  stripCapHint,
  stripRc,
  swiftIdent,
  swiftStr,
} from './naming.mjs';

const banner = (name) =>
  `// GENERATED by tools/codegen/gen-kernel.mjs from ${src(name)}. DO NOT EDIT: run \`just generate\`.\n`;

const swiftEnum = ({ doc, name, cases, props = [] }) => {
  assertUniqueIds(name, cases);
  const lines = [`/// ${docText(doc)}`, `public enum ${name}: String, CaseIterable, Sendable {`];
  for (const c of cases) {
    if (c.doc) lines.push(`  /// ${docText(c.doc)}`);
    lines.push(`  case ${swiftIdent(c.id)} = ${swiftStr(c.raw)}`);
  }
  for (const p of props) {
    lines.push(
      '',
      `  /// ${docText(p.doc)}`,
      `  public var ${p.name}: ${p.type} {`,
      '    switch self {',
    );
    for (const c of cases) lines.push(`    case .${swiftIdent(c.id)}: ${p.value(c)}`);
    lines.push('    }', '  }');
  }
  lines.push('}');
  return lines.join('\n');
};
const simpleCases = (values) => values.map((v) => ({ id: camel(v), raw: v }));
const describe = {
  doc: 'Human-readable meaning (registry text, not UI copy).',
  name: 'description',
  type: 'String',
  value: (c) => swiftStr(c.def.description),
};

export function emitSwift(reg, { schemas }) {
  const rc = reg['reason-codes'];
  const ent = reg.entitlements;
  const units = reg.units;
  const errorCodes = reg['error-codes'];
  const measurements = reg['measurement-definitions'];
  const shapes = reg['starting-shapes'];
  const out = {};

  out['ReasonCodes.swift'] = [
    banner('reason-codes'),
    swiftEnum({
      doc: 'Reason-code namespace (planning/09 §7).',
      name: 'ReasonCodeNamespace',
      cases: rc.namespaces.map((n) => ({ id: camel(stripRc(n.name)), raw: n.name, doc: n.note })),
    }),
    '',
    swiftEnum({
      doc: 'Pipeline stage (planning/09 §2) that may emit a reason code.',
      name: 'ReasonCodeStage',
      cases: simpleCases(rc.stages),
    }),
    '',
    swiftEnum({
      doc: 'Recommendation reason code (planning/09 §7): a stable identifier emitted while deciding; explanations are templated from it.',
      name: 'ReasonCode',
      cases: Object.entries(rc.codes).map(([code, def]) => ({
        id: camel(stripRc(code)),
        raw: code,
        doc: def.description,
        def,
      })),
      props: [
        {
          doc: 'Namespace the code belongs to.',
          name: 'namespace',
          type: 'ReasonCodeNamespace',
          value: (c) => `.${swiftIdent(camel(stripRc(c.def.namespace)))}`,
        },
        {
          doc: 'Stage that may emit the code.',
          name: 'stage',
          type: 'ReasonCodeStage',
          value: (c) => `.${swiftIdent(camel(c.def.stage))}`,
        },
        {
          doc: 'Names of the typed template params (planning/09 §7).',
          name: 'params',
          type: '[String]',
          value: (c) => `[${c.def.params.map(swiftStr).join(', ')}]`,
        },
        describe,
      ],
    }),
    '',
  ].join('\n');

  out['Entitlements.swift'] = [
    banner('entitlements'),
    swiftEnum({
      doc: 'Value kind of an entitlement (planning/12 §3.1).',
      name: 'EntitlementValueKind',
      cases: simpleCases(ent.kinds),
    }),
    '',
    swiftEnum({
      doc: 'Entitlement name (planning/12 §3.1): the only entitlement identifiers.',
      name: 'EntitlementName',
      cases: Object.entries(ent.entitlements).map(([name, def]) => ({
        id: camel(name),
        raw: name,
        doc: def.description,
        def,
      })),
      props: [
        {
          doc: 'Value kind of the entitlement.',
          name: 'kind',
          type: 'EntitlementValueKind',
          value: (c) => `.${swiftIdent(camel(c.def.kind))}`,
        },
        describe,
        {
          doc: 'Levels of a `level` entitlement, lowest first (planning/12 §3.2); empty for every other kind.',
          name: 'levels',
          type: '[String]',
          value: (c) => `[${(c.def.levels ?? []).map(swiftStr).join(', ')}]`,
        },
      ],
    }),
    '',
    swiftEnum({
      doc: 'Weighted generative task metered against `credits.monthly` (planning/12 §3.3).',
      name: 'CreditMeter',
      cases: simpleCases(ent.creditMeters),
    }),
    '',
  ].join('\n');

  const dims = Object.entries(units.dimensions);
  out['Units.swift'] = [
    banner('units'),
    ...dims.flatMap(([d, def]) => [
      swiftEnum({
        doc: `Canonical ${d} unit(s) (planning/06 §2): the API stores and returns SI.`,
        name: `${pascal(d)}Unit`,
        cases: simpleCases(def.units),
      }),
      '',
    ]),
    swiftEnum({
      doc: 'Measurement dimension (TS `Dimension`; renamed to avoid Foundation.Dimension).',
      name: 'MeasurementDimension',
      cases: dims.map(([d, def]) => ({ id: camel(d), raw: d, def })),
      props: [
        {
          doc: 'Raw value of the canonical (stored) unit for this dimension.',
          name: 'canonicalUnit',
          type: 'String',
          value: (c) => swiftStr(c.def.canonical),
        },
      ],
    }),
    '',
    '/// Canonical (stored) unit per dimension.',
    'public enum CanonicalUnits {',
    ...dims.map(
      ([d, def]) =>
        `  public static let ${swiftIdent(camel(d))}: ${pascal(d)}Unit = .${swiftIdent(camel(def.canonical))}`,
    ),
    '}',
    '',
    swiftEnum({
      doc: 'Display unit system selectable in the profile (planning/06 §3.1 `locale.unitSystem`).',
      name: 'UnitSystem',
      cases: simpleCases(units.unitSystems),
    }),
    '',
    swiftEnum({
      doc: 'Who produced a measurement value (planning/06 §3.1): estimated/derived values must carry confidence.',
      name: 'MeasurementSource',
      cases: simpleCases(units.measurementSources),
    }),
    '',
    '/// Exact display-conversion factors (planning/06 §3.1); storage stays SI.',
    'public enum ConversionFactors {',
    ...Object.entries(units.conversionFactors).map(
      ([k, v]) => `  public static let ${swiftIdent(k)}: Double = ${num(v)}`,
    ),
    '}',
    '',
  ].join('\n');

  out['ErrorCodes.swift'] = [
    banner('error-codes'),
    swiftEnum({
      doc: 'Error code (planning/06 §2): the stable `code` of an RFC 9457 problem the API answers. A newer server can send a code this build lacks, so `init(rawValue:)` returning nil is a case to handle.',
      name: 'ErrorCode',
      cases: Object.entries(errorCodes.codes).map(([code, def]) => ({
        id: camel(code),
        raw: code,
        doc: def.description,
        def,
      })),
      props: [
        {
          doc: 'HTTP status the API answers the code with.',
          name: 'status',
          type: 'Int',
          value: (c) => int(c.def.status),
        },
        {
          doc: 'RFC 9457 `title` (registry text, not UI copy).',
          name: 'title',
          type: 'String',
          value: (c) => swiftStr(c.def.title),
        },
        describe,
      ],
    }),
    '',
  ].join('\n');

  out['MeasurementDefinitions.swift'] = [
    banner('measurement-definitions'),
    swiftEnum({
      doc: 'Body measurement (planning/07 §3.3) with its dimension, stored unit and hard bounds. Both bounds are inclusive: a value equal to one is accepted. Outside them the API answers `MEASUREMENT_IMPLAUSIBLE` and never stores or clamps the value.',
      name: 'MeasurementId',
      cases: Object.entries(measurements.measurements).map(([id, def]) => ({
        id: camel(id),
        raw: id,
        def,
      })),
      props: [
        {
          doc: 'Unit dimension of the measurement.',
          name: 'dimension',
          type: 'MeasurementDimension',
          value: (c) => `.${swiftIdent(camel(c.def.dimension))}`,
        },
        {
          doc: "Raw value of the stored unit: the dimension's canonical unit.",
          name: 'unit',
          type: 'String',
          value: (c) => swiftStr(c.def.unit),
        },
        // Not `min`/`max`: those would shadow `Swift.min(_:_:)` and `max(_:_:)` in extensions.
        {
          doc: 'Smallest accepted value, inclusive, in `unit` (registry `min`).',
          name: 'minimum',
          type: 'Double',
          value: (c) => num(c.def.min),
        },
        {
          doc: 'Largest accepted value, inclusive, in `unit` (registry `max`).',
          name: 'maximum',
          type: 'Double',
          value: (c) => num(c.def.max),
        },
      ],
    }),
    '',
  ].join('\n');

  out['StartingShapes.swift'] = [
    banner('starting-shapes'),
    swiftEnum({
      doc: 'Avatar starting shape offered at onboarding (planning/07 §3.1), in display order. The case docs are registry text, not UI copy.',
      name: 'StartingShape',
      cases: Object.entries(shapes.shapes).map(([id, def]) => ({
        id: camel(id),
        raw: id,
        doc: def.description,
      })),
    }),
    '',
    '/// Starting-shape constants (planning/07 §3.1).',
    'public enum StartingShapes {',
    '  /// The shape preselected when the person makes no choice.',
    `  public static let defaultShape: StartingShape = .${swiftIdent(camel(shapes.default))}`,
    '  /// Base mesh id every starting shape starts from.',
    `  public static let baseMesh: String = ${swiftStr(shapes.baseMesh)}`,
    '}',
    '',
  ].join('\n');

  out['CaptureRules.swift'] = emitCaptureRules(
    reg['capture-rules'],
    integerKeys(schemas['capture-rules']),
  );
  return out;
}

const hintCase = (key) => camel(stripCapHint(key));
const optional = (value, render) => (value === undefined ? 'nil' : render(value));
const captureConstant = (path, k, v, intKeys) =>
  `public static let ${swiftIdent(k)}: ${intKeys.has(path) ? `Int = ${int(v)}` : `Double = ${num(v)}`}`;

function emitCaptureRules(cr, intKeys) {
  return [
    banner('capture-rules'),
    swiftEnum({
      doc: 'How the item is photographed (capture brief §2).',
      name: 'CaptureMode',
      cases: simpleCases(cr.captureModes),
    }),
    '',
    swiftEnum({
      doc: 'Blocking check that keeps the shutter locked, highest priority first (capture brief §4).',
      name: 'CaptureLockReason',
      cases: simpleCases(cr.lockReasons),
    }),
    '',
    swiftEnum({
      doc: 'Body keypoint read by the worn-mode body check (capture brief §3).',
      name: 'CaptureBodyPart',
      cases: cr.bodyParts.map((p) => ({ id: p, raw: p })),
    }),
    '',
    swiftEnum({
      doc: 'Hint class: blocking (shutter locked), advisory (never locks) or status.',
      name: 'CaptureHintKind',
      cases: simpleCases(captureHintKinds(cr)),
    }),
    '',
    swiftEnum({
      doc: 'Hint key, also the hint label test ID, in priority order (capture brief §6).',
      name: 'CaptureHint',
      cases: Object.entries(cr.hints).map(([key, def]) => ({ id: hintCase(key), raw: key, def })),
      props: [
        {
          doc: 'Hint class.',
          name: 'kind',
          type: 'CaptureHintKind',
          value: (c) => `.${swiftIdent(camel(c.def.kind))}`,
        },
        {
          doc: 'Lock reason this hint reports, if any.',
          name: 'lockReason',
          type: 'CaptureLockReason?',
          value: (c) => optional(c.def.lockReason, (r) => `.${swiftIdent(camel(r))}`),
        },
      ],
    }),
    '',
    swiftEnum({
      doc: 'Shape family picked before capture (capture brief §2); not a closet taxonomy id.',
      name: 'CaptureShapeFamily',
      cases: Object.entries(cr.families).map(([id, def]) => ({ id: camel(id), raw: id, def })),
      props: [
        {
          doc: 'Too small below this box area share (flat and hanger modes).',
          name: 'minAreaShare',
          type: 'Double',
          value: (c) => num(c.def.minAreaShare),
        },
        {
          doc: 'Capture modes offered.',
          name: 'modes',
          type: '[CaptureMode]',
          value: (c) => `[${c.def.modes.map((m) => `.${swiftIdent(camel(m))}`).join(', ')}]`,
        },
        {
          doc: 'Body parts that must all be present in worn mode; empty means no body check.',
          name: 'wornRequiredParts',
          type: '[CaptureBodyPart]',
          value: (c) => `[${c.def.wornRequiredParts.map((p) => `.${swiftIdent(p)}`).join(', ')}]`,
        },
        {
          doc: 'Hint shown when a required body part is missing.',
          name: 'wornHint',
          type: 'CaptureHint?',
          value: (c) => optional(c.def.wornHint, (h) => `.${swiftIdent(hintCase(h))}`),
        },
      ],
    }),
    '',
    '/// Live-check thresholds, counts and timings (capture brief §3-§5). Ms = milliseconds.',
    'public enum CaptureRules {',
    ...Object.entries(cr)
      .filter(([, v]) => typeof v === 'number')
      .map(([k, v]) => `  ${captureConstant(k, k, v, intKeys)}`),
    ...Object.entries(cr)
      .filter(([, v]) => isNumberBlock(v))
      .flatMap(([block, values]) => [
        '',
        `  public enum ${pascal(block)} {`,
        ...Object.entries(values).map(
          ([k, v]) => `    ${captureConstant(`${block}.${k}`, k, v, intKeys)}`,
        ),
        '  }',
      ]),
    '}',
    '',
  ].join('\n');
}
