// Declaration tree -> Swift for the Foundation-free `DesignTokens` target (DEC-87:
// apps/ios/Packages/DesignSystem/Sources/DesignTokens/generated/). Plain value types only (Double,
// Int, String, UInt32 ARGB), so the target compiles under Swift 6 strict concurrency on Linux; the
// SwiftUI `DesignSystem` target maps them to Color and Font. Every type is `nonisolated` because
// the package sets `defaultIsolation(MainActor.self)` and these are immutable Sendable values,
// usable from any isolation domain (the Core convention, e.g. AppConfig). Layout follows
// apps/ios/.swift-format: 2-space indent, 120 columns, grouped hex literals.
import { docText, num, swiftIdent, swiftStr } from './naming.mjs';
import { joinMembers, renderDeclaration, renderTiers, valueLines } from './render.mjs';

const INDENT = '  ';
const TYPE = {
  double: 'Double',
  int: 'Int',
  string: 'String',
  color: 'UInt32',
  role: 'AppColorRole',
  textStyle: 'AppTextStyle',
  stringList: '[String]',
  doubleList: '[Double]',
};
/** `role?` -> `AppColorRole?`, `list:ButtonLook` -> `[ButtonLook]`, a struct name as is. */
const typeName = (type) => {
  if (type.endsWith('?')) return `${typeName(type.slice(0, -1))}?`;
  if (type.startsWith('list:')) return `[${typeName(type.slice('list:'.length))}]`;
  return TYPE[type] ?? type;
};

export const swift = {
  extension: 'swift',
  indent: INDENT,
  limit: 120,
  wrapAfterAssign: false,
  callTrailingComma: false,
  list: { open: '[', close: ']', empty: '[]' },
  argLabel: (name) => `${swiftIdent(name)}: `,
  spell: {
    double: num,
    string: swiftStr,
    role: (id) => `.${swiftIdent(id)}`,
    ref: (namespace, member) => `${namespace}.${swiftIdent(member)}`,
    enumCase: (_type, id) => `.${swiftIdent(id)}`,
    none: 'nil',
  },
  header: (source, title) => [
    '// GENERATED by tools/codegen/gen-tokens.mjs. DO NOT EDIT: run `just generate`.',
    `// Source: ${source}`,
    `// ${title} (DEC-87).`,
  ],
  doc: (text, pad) => `${pad}/// ${docText(text)}`,
  namespaceHead: (name) => `nonisolated public enum ${name}`,
  emptyNamespace: (name) => `nonisolated public enum ${name} {}`,
  constant(member, depth) {
    const pad = INDENT.repeat(depth);
    const id = swiftIdent(member.name);
    const head =
      member.value.t === 'init'
        ? `${pad}public static let ${id} = `
        : `${pad}public static let ${id}: ${typeName(member.type)} = `;
    return valueLines(swift, head, member, pad);
  },
  struct(decl, depth) {
    const pad = INDENT.repeat(depth);
    const inner = pad + INDENT;
    const fields = decl.fields.map(
      (f) => `${inner}public let ${swiftIdent(f.name)}: ${typeName(f.type)}`,
    );
    const nested = decl.nested.map((n) => renderDeclaration(swift, n, depth + 1));
    const instances = decl.instances.map(({ name, value }) =>
      valueLines(swift, `${inner}public static let ${swiftIdent(name)} = `, { value }, inner),
    );
    const lookup = decl.lookup ? [lookupLines(decl, inner)] : [];
    const find = decl.find ? [findLines(decl.find, inner)] : [];
    return [
      ...(decl.doc ? [swift.doc(decl.doc, pad)] : []),
      `${pad}nonisolated public struct ${decl.name}: Sendable, Equatable {`,
      ...joinMembers([fields, ...nested, ...instances, ...lookup, ...find]),
      `${pad}}`,
    ];
  },
  /**
   * A closed set of kebab ids: the case is the Swift name, the raw value the id. Each extra string
   * field (`decl.fields`) is a computed property switching over the cases.
   */
  enum(decl) {
    const cases = decl.cases.map(({ name, id }) => {
      const raw = name === id ? '' : ` = ${swiftStr(id)}`;
      return `${INDENT}case ${swiftIdent(name)}${raw}`;
    });
    const properties = (decl.fields ?? []).map((field) => fieldLines(decl, field, INDENT));
    return [
      `/// ${docText(decl.doc)}`,
      `nonisolated public enum ${decl.name}: String, CaseIterable, Sendable {`,
      ...joinMembers([cases, ...properties]),
      '}',
    ];
  },
  roles: (decl) => swift.enum(decl),
};

/** `title`: a string per case, as a computed property switching over the cases. */
function fieldLines(decl, field, pad) {
  const step = pad + INDENT;
  return [
    `${pad}/// ${docText(field.doc)}`,
    `${pad}public var ${swiftIdent(field.name)}: String {`,
    `${step}switch self {`,
    ...decl.cases.map((c) => `${step}case .${swiftIdent(c.name)}: ${swiftStr(c[field.name])}`),
    `${step}}`,
    `${pad}}`,
  ];
}

/** `colors[role]`: a switch over every role (one case per field). */
function lookupLines(decl, pad) {
  const step = pad + INDENT;
  const { roleType, valueType } = decl.lookup;
  return [
    `${pad}/// The value of \`role\` in this context.`,
    `${pad}public subscript(role: ${roleType}) -> ${typeName(valueType)} {`,
    `${step}switch role {`,
    ...decl.fields.map(({ name }) => `${step}case .${swiftIdent(name)}: ${swiftIdent(name)}`),
    `${step}}`,
    `${pad}}`,
  ];
}

/** `appearance(variant:size:state:)`: the matching list item's result, or nil when none matches. */
function findLines(find, pad) {
  const params = find.keys.map(({ name, type }) => `${swiftIdent(name)}: ${typeName(type)}`);
  const head = `${pad}public func ${find.name}(`;
  const tail = `) -> ${typeName(find.resultType)}? {`;
  const single = `${head}${params.join(', ')}${tail}`;
  const wrapped = params.map((p, i) => `${pad}${INDENT}${p}${i < params.length - 1 ? ',' : ''}`);
  const signature = single.length <= swift.limit ? [single] : [head, ...wrapped, `${pad}${tail}`];
  const match = find.keys.map(({ name }) => `$0.${name} == ${swiftIdent(name)}`).join(' && ');
  return [
    `${pad}/// ${docText(find.doc)}`,
    ...signature,
    `${pad}${INDENT}${find.list}.first { ${match} }?.${find.result}`,
    `${pad}}`,
  ];
}

/** `{ ReferenceTokens.swift, SchemeTokens.swift, ComponentTokens.swift }`. */
export const emitSwift = (tiers, source) => renderTiers(swift, tiers, source);
