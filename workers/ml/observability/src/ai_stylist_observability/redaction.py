"""Log redaction (planning/11 §8): the forbidden key words and the structlog processor that drops
them, and the allowlist a logged exception is reduced to. Pure code; each service's `main.py`
wires the processors into logging and `tracing.py` applies the same words to span attributes.

The words are `FORBIDDEN_LOG_KEYS` of `ai_stylist_generated.kernel`, generated by `just generate`
from the single source `packages/shared-kernel/registry/forbidden-log-keys.json` (the generated
member ships in the image, so nothing reads `packages/` at run time). The matching mirrors
`isForbiddenLogKey` in `apps/api/src/platform/logger.ts`: a key is forbidden when the whole
key, or any of its camelCase / snake_case / kebab-case words, is a forbidden word
(`userEmail`, `refresh_token` and `x-auth-token` are forbidden; `latency` and `userId` are not).

A logged exception mirrors the API logger's `err` serializer (`serializeErr`, with
`apps/api/src/platform/errors/error-shape.ts` for each link). The class-name shape, the code
shape and the cause depth are `ERROR_NAME_SHAPE`, `CODE_SHAPE` and `MAX_CAUSE_DEPTH` of
`ai_stylist_generated.kernel`, generated from `packages/shared-kernel/registry/log-redaction.json`
(each shape compiled with `re.ASCII` and always used with `fullmatch`). A summary is
`{type, code?, cause?}` only, under `err` for the exception being logged (`exc_info`) and in place
of an exception under any other key.
Never the message, the traceback or another attribute: a driver error's message echoes row values,
and a wrapper's message can list statement parameters. A `code` property that raises counts as
no code. Any other value under `err` is `{type}` only: the API writes a non-Error by its JavaScript
`typeof`, the worker by its Python class name (`str`, `dict`).

The event is only the string the caller wrote: printf-style arguments are dropped, never
interpolated (`drop_positional_args`; stdlib records keep their template), as the API logger's
`hooks.logMethod` drops them. A stdlib message that is not a string is written as its class name.

`_scrub` walks every mapping, list, tuple, set and frozenset. A container that holds itself is
written as `[Circular]`; unlike the API's `redactForbidden`, which marks every repeated reference,
a reference repeated outside a cycle is written in full. A value JSON cannot encode is written as
its class name (`json_default`), never its repr. Unlike the API, which writes `[REDACTED]`, a
forbidden key is dropped and counted under `redacted_keys`.

Not covered, as in the API: free text the caller builds into the event itself
(`log.error(f"failed: {error}")`).
"""

from __future__ import annotations

import logging
import re
import sys
from collections.abc import Mapping, MutableMapping
from typing import Any

from ai_stylist_generated.kernel import (
    CODE_SHAPE,
    ERROR_NAME_SHAPE,
    FORBIDDEN_LOG_KEYS,
    MAX_CAUSE_DEPTH,
)

REDACTED_COUNT_KEY = "redacted_keys"

# `WORD_SPLIT` in apps/api/src/platform/logger.ts: runs of non-alphanumerics, and the boundary
# between a lowercase letter or digit and an uppercase letter.
_WORD_SPLIT = re.compile(r"[^a-zA-Z0-9]+|(?<=[a-z0-9])(?=[A-Z])")


def is_forbidden_log_key(key: str) -> bool:
    """True when `key`, or one of its camel/snake/kebab words, is a forbidden word."""
    if key.lower() in FORBIDDEN_LOG_KEYS:
        return True
    return any(word.lower() in FORBIDDEN_LOG_KEYS for word in _WORD_SPLIT.split(key) if word)


# The log field of the exception being logged, as the API logger's `err`.
ERR_KEY = "err"
# What `_scrub` writes for a container already on the path from the root (a reference cycle).
CIRCULAR = "[Circular]"


def type_name(value: object) -> str:
    """The class name of `value` when it is name-shaped, else `Error`."""
    name = type(value).__name__
    return name if ERROR_NAME_SHAPE.fullmatch(name) else "Error"


def _code_of(error: BaseException) -> str | None:
    """A code-shaped `code` attribute, or `None`. A `code` property that raises counts as none:
    letting it escape would hand the record to `logging.Handler.handleError`."""
    try:
        code = getattr(error, "code", None)
    except Exception:
        return None
    return code if isinstance(code, str) and CODE_SHAPE.fullmatch(code) else None


def _cause_of(error: BaseException) -> BaseException | None:
    """The next link of the chain Python's own traceback prints: the explicit cause (`raise ... from
    cause`), else the exception being handled when it was raised, unless `from None` hid it."""
    if error.__cause__ is not None:
        return error.__cause__
    return None if error.__suppress_context__ else error.__context__


def summarize_error(error: BaseException, depth: int = 0) -> dict[str, Any]:
    """Everything of an exception that may reach a log line: its class name, a code-shaped `code`
    attribute, and the same for at most `MAX_CAUSE_DEPTH` links of its cause chain."""
    summary: dict[str, Any] = {"type": type_name(error)}
    code = _code_of(error)
    if code is not None:
        summary["code"] = code
    cause = _cause_of(error) if depth < MAX_CAUSE_DEPTH else None
    if cause is not None:
        summary["cause"] = summarize_error(cause, depth + 1)
    return summary


def _logged_exception(exc_info: Any) -> BaseException | None:
    """The exception an `exc_info` value names: an exception, an `exc_info` tuple, or a truthy
    value meaning the exception being handled (`log.exception(...)`)."""
    if isinstance(exc_info, BaseException):
        return exc_info
    if isinstance(exc_info, tuple) and len(exc_info) == 3:  # (type, value, traceback)
        _type, value, _traceback = exc_info
        return value if isinstance(value, BaseException) else None
    return sys.exception() if exc_info else None


def summarize_exc_info(
    _logger: Any, _method_name: str, event_dict: MutableMapping[str, Any]
) -> MutableMapping[str, Any]:
    """structlog processor in place of `format_exc_info`: replaces `exc_info` with the
    `summarize_error` allowlist under `err`, so no message or traceback is rendered. Without a
    logged exception, a value the caller put under `err` (`err=str(exc)`, a dict, stdlib
    `extra={"err": ...}`) is the same allowlist when it is an exception, else `{type}` only, as the
    API's `err` serializer writes a non-Error throw by its type."""
    exc_info = event_dict.pop("exc_info", None)
    error = _logged_exception(exc_info)
    if error is not None:
        event_dict[ERR_KEY] = summarize_error(error)
    elif ERR_KEY in event_dict:
        value = event_dict[ERR_KEY]
        event_dict[ERR_KEY] = (
            summarize_error(value)
            if isinstance(value, BaseException)
            else {"type": type_name(value)}
        )
    return event_dict


# Where structlog's stdlib `BoundLogger` keeps `log.info("user %s", value)`'s `value`.
POSITIONAL_ARGS_KEY = "positional_args"


def drop_positional_args(
    _logger: Any, _method_name: str, event_dict: MutableMapping[str, Any]
) -> MutableMapping[str, Any]:
    """structlog processor: the event is only the string the caller wrote. printf-style arguments
    are dropped, never interpolated, as the API logger's `hooks.logMethod` drops them: `"failed
    %s" % exc` would write the exception's message past every other processor."""
    event_dict.pop(POSITIONAL_ARGS_KEY, None)
    return event_dict


def caller_message_only(
    _logger: Any, _method_name: str, event_dict: MutableMapping[str, Any]
) -> MutableMapping[str, Any]:
    """`foreign_pre_chain` step for stdlib records: a message that is not a string
    (`log.error(exc)`) is written as its class name (`type_name`), not as its `str()`. With the
    formatter's `use_get_message=False`, a string message is its template, uninterpolated."""
    record = event_dict.get("_record")
    if isinstance(record, logging.LogRecord) and not isinstance(record.msg, str):
        event_dict["event"] = type_name(record.msg)
    return event_dict


def _scrub(value: Any, path: set[int] | None = None) -> tuple[Any, int]:
    """Return a copy of `value` with forbidden keys removed at every depth + a drop count. An
    exception, under any key and at any depth, becomes its `summarize_error` allowlist. Every
    mapping is walked (a read-only `MappingProxyType` too), and lists, tuples, sets and frozensets
    become lists. Every key is written as `str(key)`, the string the forbidden-key match checks:
    `JSONRenderer(sort_keys=True)` cannot order a mapping that mixes `int` and `str` keys, and the
    failed line would be dropped silently. `path` holds the ids of the containers being walked: a
    container that holds itself is written as `[Circular]` (a reference repeated outside a cycle is
    written in full)."""
    if isinstance(value, BaseException):
        return summarize_error(value), 0
    if not isinstance(value, Mapping | list | tuple | set | frozenset):
        return value, 0
    path = set() if path is None else path
    if id(value) in path:
        return CIRCULAR, 0
    path.add(id(value))
    try:
        if isinstance(value, Mapping):
            dropped = 0
            cleaned: dict[str, Any] = {}
            for key, inner in value.items():
                name = str(key)
                if is_forbidden_log_key(name):
                    dropped += 1
                    continue
                cleaned[name], inner_dropped = _scrub(inner, path)
                dropped += inner_dropped
            return cleaned, dropped
        items = [_scrub(item, path) for item in value]
        return [item for item, _ in items], sum(count for _, count in items)
    finally:
        path.discard(id(value))


def json_default(value: object) -> str:
    """`JSONRenderer`'s `default=` for a value JSON cannot encode: its class name, never its
    `repr()` (structlog's own fallback), which can be any text."""
    return type_name(value)


def redact_forbidden_keys(
    _logger: Any, _method_name: str, event_dict: MutableMapping[str, Any]
) -> MutableMapping[str, Any]:
    """structlog processor: drop every forbidden key; record how many were dropped."""
    cleaned, dropped = _scrub(event_dict)
    if dropped:
        cleaned[REDACTED_COUNT_KEY] = dropped
    return cleaned
