// In-process tests for the Kotlin emitter (emit-kotlin.mjs) over the declaration tree
// (declarations.mjs): the package, the reference scales, the colour roles and their five AppColors
// contexts, and one <Component>Tokens data class per component with one companion instance per
// context. The repository DESIGN.md is emitted too, for the owner's naming decisions and the
// ktlint_official layout. Run by scripts/test/design-tokens.test.sh.
import assert from 'node:assert/strict';
import { test } from 'node:test';

import { emitKotlin } from '../emit-kotlin.mjs';
import {
  REPO_DESIGN_MD,
  VALID,
  block,
  emitted,
  firstGroups,
  modelOf,
  modelOfEdited,
} from './models.mjs';

const files = emitted(emitKotlin, modelOf(VALID));
const reference = files['ReferenceTokens.kt'];
const scheme = files['SchemeTokens.kt'];
const component = files['ComponentTokens.kt'];
const repo = emitted(emitKotlin, modelOf(REPO_DESIGN_MD));

test('three tier files in the generated package, deterministic', () => {
  const names = ['ReferenceTokens.kt', 'SchemeTokens.kt', 'ComponentTokens.kt'];
  assert.deepEqual(Object.keys(files), names);
  for (const text of Object.values(files)) {
    assert.match(text, /^\/\/ GENERATED by tools\/codegen\/gen-tokens\.mjs\. DO NOT EDIT/);
    assert.match(text, /\npackage app\.aistylist\.core\.designsystem\.generated\n\n/);
    assert.ok(text.endsWith('}\n'), 'ends with one newline');
  }
  assert.deepEqual(emitted(emitKotlin, modelOf(VALID)), files);
});

test('reference scales: objects of Double vals; numeric keys get the scale prefix', () => {
  const spacing = [
    'object AppSpacing {',
    '    val space4: Double = 4.0',
    '    val space8: Double = 8.0',
    '    val space16: Double = 16.0',
    '',
    '    val all: List<AppScaleStep> =',
    '        listOf(',
    '            AppScaleStep(name = "spacing-4", value = AppSpacing.space4),',
    '            AppScaleStep(name = "spacing-8", value = AppSpacing.space8),',
    '            AppScaleStep(name = "spacing-16", value = AppSpacing.space16),',
    '        )',
    '}',
  ];
  assert.equal(block(reference, 'object AppSpacing'), spacing.join('\n'));
  assert.match(reference, /\n {4}val radius4: Double = 4\.0\n/);
  const full = /\n {12}AppScaleStep\(name = "rounded-full", value = AppRadius\.full\),\n/;
  assert.match(reference, full);
  const step = ['data class AppScaleStep(', '    val name: String,', '    val value: Double,', ')'];
  assert.equal(block(reference, 'data class AppScaleStep('), step.join('\n'));
});

test('type styles: a multiline AppTextStyle value starts on the line after its `=`', () => {
  const head = /\ndata class AppTextStyle\(\n {4}val name: String,\n {4}val fontFamily: String,\n/;
  assert.match(reference, head);
  assert.match(reference, /\n {4}val m3Roles: List<String>,\n\)\n/);
  const label = [
    '    val label: AppTextStyle =',
    '        AppTextStyle(',
    '            name = "label",',
    '            fontFamily = "Fixture Sans",',
    '            fontSize = 12.0,',
    '            fontWeight = 600,',
    '            lineHeight = 16.0,',
    '            letterSpacing = 0.6,',
    '            dynamicType = "caption",',
    '            m3Roles = listOf("bodyMedium", "bodySmall", "labelLarge", "labelMedium", "labelSmall"),',
    '        )',
  ];
  assert.equal(block(reference, 'val label: AppTextStyle =', 4), label.join('\n'));
  assert.match(reference, /\n {12}m3Roles = emptyList\(\),\n/);
  const all = [
    '    val all: List<AppTextStyle> =',
    '        listOf(',
    '            AppTypography.heading,',
    '            AppTypography.body,',
    '            AppTypography.label,',
    '            AppTypography.badge,',
    '        )',
    '}',
  ];
  // Last in the object, so every style is initialised before the list reads it.
  assert.ok(reference.includes(`\n\n${all.join('\n')}\n`), 'AppTypography.all, last, in key order');
});

test('elevation and motion: groups are nested objects; curves are lists; aliases are refs', () => {
  const sheet = [
    '    object Sheet {',
    '        val offsetY: Double = -4.0',
    '        val blur: Double = 16.0',
    '        val color: AppColorRole = AppColorRole.SCRIM',
    '    }',
  ];
  assert.equal(block(reference, 'object Sheet'), sheet.join('\n'));
  const easing = /\n {4}val easingEnter: List<Double> = listOf\(0\.2, 0\.0, 0\.0, 1\.0\)\n/;
  assert.match(reference, easing);
  const edited = modelOfEdited((fm) => {
    fm.elevation.sheet.color = 'rgba(27,27,25,0.14)';
    fm.motion.sheet = { duration: '250ms', easing: '{motion.easing-enter}' };
  });
  const text = emitted(emitKotlin, edited)['ReferenceTokens.kt'];
  assert.match(text, /\n {8}val color: Long = 0x241B_1B19\n/);
  assert.match(text, /\n {8}val easing: List<Double> = AppMotion\.easingEnter\n/);
});

test('colour roles: an enum entry per role, its DESIGN.md key first, reads its own property', () => {
  const head = ['enum class AppColorRole(', '    val id: String,', '    internal val read'];
  assert.ok(scheme.includes(head.join('\n')), '`id` is the first constructor parameter');
  const entries = [...scheme.matchAll(/^ {4}([A-Z0-9_]+)\("([a-z0-9-]+)", AppColors::(\w+)\),$/gm)];
  const triples = entries.map((m) => m.slice(1));
  assert.deepEqual(triples, [
    ['BACKGROUND', 'background', 'background'],
    ['TEXT', 'text', 'text'],
    ['PRIMARY', 'primary', 'primary'],
    ['PRIMARY_PRESSED', 'primary-pressed', 'primaryPressed'],
    ['ON_PRIMARY', 'on-primary', 'onPrimary'],
    ['SURFACE2', 'surface-2', 'surface2'],
    ['SCRIM', 'scrim', 'scrim'],
    ['RING_LIGHT', 'ring-light', 'ringLight'],
  ]);
  const lookup = /\n {4}operator fun get\(role: AppColorRole\): Long = role\.read\(this\)\n/;
  assert.match(scheme, lookup);
});

test('AppColors: a data class with one companion instance per context', () => {
  const instances = firstGroups(scheme, /^ {8}val (\w+): AppColors =$/gm);
  assert.deepEqual(instances, ['light', 'dark', 'brand', 'hcLight', 'hcDark']);
  const brand = block(scheme, 'val brand: AppColors =', 4);
  assert.match(brand, /\n {16}background = 0xFF22_5533,\n/);
  assert.match(brand, /\n {16}primary = 0xFF99_CCFF,\n/);
  assert.match(scheme, /\n {16}scrim = 0x8000_0000,\n/);
});

test('a component: a data class, nested state classes, companion instances per context', () => {
  const tokens = block(component, 'data class ButtonPrimaryTokens(');
  const head = [
    'data class ButtonPrimaryTokens(',
    '    val backgroundColor: AppColorRole,',
    '    val textColor: AppColorRole,',
  ];
  assert.ok(tokens.startsWith(head.join('\n')), 'the class header');
  const nested = [
    '    val pressed: Pressed,',
    ') {',
    '    data class Pressed(',
    '        val backgroundColor: AppColorRole,',
    '    )',
    '',
    '    companion object {',
    '        val light: ButtonPrimaryTokens =',
    '            ButtonPrimaryTokens(',
    '                backgroundColor = AppColorRole.PRIMARY,',
  ];
  assert.ok(tokens.includes(nested.join('\n')), 'the nested state class and the companion');
  const pressed = [
    '                pressed = Pressed(backgroundColor = AppColorRole.PRIMARY_PRESSED),',
    '            )',
  ];
  assert.ok(tokens.includes(pressed.join('\n')), 'a short nested value stays on one line');
});

test('an unpaired component keeps its full key; a long instance wraps after its `=`', () => {
  assert.match(component, /\ndata class ChipOutlineLightTokens\(\n/);
  assert.match(component, /\n {8}val hcDark: OverlayTokens =\n {12}OverlayTokens\(\n/);
});

test('a scheme-dependent value differs per context instance', () => {
  const edited = modelOfEdited((fm) => {
    fm.components['button-primary-pressed-dark'].backgroundColor = '{colors.primary-dark}';
  });
  const text = emitted(emitKotlin, edited)['ComponentTokens.kt'];
  const pressed = firstGroups(text, /pressed = Pressed\(backgroundColor = AppColorRole\.(\w+)\)/g);
  const expected = ['PRIMARY_PRESSED', 'PRIMARY', 'PRIMARY', 'PRIMARY_PRESSED', 'PRIMARY'];
  assert.deepEqual(pressed, expected);
});

test('an unpaired component has instances only for the contexts that draw from its scheme', () => {
  const instances = (text, type) => {
    const body = block(text, `data class ${type}(`);
    return firstGroups(body, new RegExp(`^ {8}val (\\w+): ${type} =`, 'gm'));
  };
  assert.deepEqual(instances(component, 'ChipOutlineLightTokens'), ['light', 'hcLight']);
  const banner = instances(repo['ComponentTokens.kt'], 'BannerDarkTokens');
  assert.deepEqual(banner, ['dark', 'brand', 'hcDark']);
});

test('the repository DESIGN.md: owner naming decisions of 2026-10-20', () => {
  const types = new Set(firstGroups(repo['ComponentTokens.kt'], /^data class (\w+)\(/gm));
  for (const name of ['BannerDarkTokens', 'CameraModeSwitchTokens', 'CameraModeSelectedTokens']) {
    assert.ok(types.has(name), `${name} is emitted`);
  }
  for (const name of ['BannerTokens', 'CameraModeTokens']) {
    assert.ok(!types.has(name), `${name} is not emitted`);
  }
  assert.match(repo['ReferenceTokens.kt'], /\n {4}object SheetLight \{\n/);
});

test('ktlint_official layout: 120 columns, 4-space indents, trailing commas, wrapped values', () => {
  for (const [file, text] of [...Object.entries(files), ...Object.entries(repo)]) {
    const lines = text.split('\n');
    lines.forEach((line, i) => {
      const at = `${file}:${i + 1}`;
      assert.ok(line.length <= 120, `${at} is ${line.length} columns`);
      assert.ok(!/\t| $/.test(line), `${at} has a tab or a trailing space`);
      assert.equal(/^ */.exec(line)[0].length % 4, 0, `${at} indent`);
      assert.ok(!/= \S+\($/.test(line), `${at}: a multiline value starts on its own line`);
      assert.ok(!/\{\}$/.test(line), `${at}: an empty class body`);
      if (/^ *\)( \{)?,?$/.test(lines[i + 1] ?? '')) {
        assert.ok(line.endsWith(','), `${at}: a multiline list ends with a trailing comma`);
      }
    });
  }
});
