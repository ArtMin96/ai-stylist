// In-process tests for the component API emitters (emit-api-swift.mjs, emit-api-kotlin.mjs) over
// api-declarations.mjs: the enums with their contract ids, the test-ID constants, the merged-look
// tables per context with their lookup, and the gallery, for the synthetic contract fixture and
// the repository button contract. Parity between the two files: parity.test.mjs. Run by
// scripts/test/design-tokens.test.sh.
import assert from 'node:assert/strict';
import { test } from 'node:test';

import { emitApiKotlin } from '../emit-api-kotlin.mjs';
import { emitApiSwift } from '../emit-api-swift.mjs';
import {
  CONTRACT_TOKENS,
  REPO_CONTRACTS,
  REPO_DESIGN_MD,
  VALID_CONTRACTS,
  block,
  emittedApi,
  firstGroups,
  modelOf,
  once,
} from './models.mjs';

const fixtureModel = modelOf(CONTRACT_TOKENS);
const repoModel = modelOf(REPO_DESIGN_MD);
const swift = emittedApi(emitApiSwift, fixtureModel, VALID_CONTRACTS)['ComponentAPI.swift'];
const kotlin = emittedApi(emitApiKotlin, fixtureModel, VALID_CONTRACTS)['ComponentApi.kt'];
const repoApi = (emit, file) => once(() => emittedApi(emit, repoModel, REPO_CONTRACTS)[file]);
const repoSwift = repoApi(emitApiSwift, 'ComponentAPI.swift');
const repoKotlin = repoApi(emitApiKotlin, 'ComponentApi.kt');
const CONTEXT_IDS = ['light', 'dark', 'brand', 'hcLight', 'hcDark'];

test('one API file per language, with the generated header, deterministic', () => {
  for (const text of [swift, kotlin]) {
    assert.match(text, /^\/\/ GENERATED by tools\/codegen\/gen-tokens\.mjs\. DO NOT EDIT/);
    assert.match(text, /\n\/\/ Source: components\/\*\.yaml \+ DESIGN\.md\n/);
    assert.ok(text.endsWith('}\n'), 'ends with one newline');
  }
  assert.match(kotlin, /\npackage app\.aistylist\.core\.designsystem\.generated\n/);
  const again = emittedApi(emitApiSwift, fixtureModel, VALID_CONTRACTS)['ComponentAPI.swift'];
  assert.equal(again, swift);
});

test('Swift enums: a case per id, the raw value only where it differs from the case', () => {
  const variant = [
    'nonisolated public enum ButtonVariant: String, CaseIterable, Sendable {',
    '  case primary',
    '  case secondary',
    '}',
  ];
  assert.equal(block(swift, 'nonisolated public enum ButtonVariant'), variant.join('\n'));
  const repoVariant = block(repoSwift(), 'nonisolated public enum ButtonVariant');
  assert.match(repoVariant, /\n {2}case primaryOutline = "primary-outline"\n/);
  assert.match(repoVariant, /\n {2}case destructiveFilled = "destructive-filled"\n/);
  const states = block(repoSwift(), 'nonisolated public enum ButtonState');
  const cases = ['enabled', 'pressed', 'focused', 'disabled', 'loading'];
  assert.deepEqual(firstGroups(states, /case (\w+)/g), cases);
});

test('Kotlin enums: an entry per id carrying the contract id', () => {
  const size = ['enum class ButtonSize(', '    val id: String,', ') {'];
  assert.ok(kotlin.includes(size.join('\n')), 'the ButtonSize header');
  assert.match(kotlin, /\n {4}LARGE\("large"\),\n {4}SMALL\("small"\),\n\}\n/);
  assert.match(repoKotlin(), /\n {4}PRIMARY_OUTLINE\("primary-outline"\),\n/);
});

test('test IDs: one constant per allowed combination and no other', () => {
  const ids = firstGroups(swift, /public static let \w+: String = "(ds-[a-z-]+)"/g);
  assert.equal(ids.length, 14);
  assert.ok(ids.includes('ds-button-primary-small-disabled'));
  assert.ok(!ids.includes('ds-button-secondary-small-enabled'), 'secondary has no small');
  assert.match(swift, /\n {2}public static let secondaryLargeFocused: String = /);
  assert.match(kotlin, /\n {4}val secondaryLargeFocused: String = "ds-button-secondary-large-/);
  const repoIds = firstGroups(repoSwift(), /: String = "(ds-button-[a-z-]+)"/g);
  assert.equal(repoIds.length, 100);
  assert.ok(repoIds.includes('ds-button-text-compact-enabled'));
  assert.ok(!repoIds.some((id) => id.startsWith('ds-button-text-small-')), 'text small is gone');
  for (const text of [repoSwift(), repoKotlin()]) assert.doesNotMatch(text, /textSmall|TEXT_SMALL/);
});

test('the merged look: optional where a look lacks the property, the focus ring as a type', () => {
  const appearance = block(swift, 'nonisolated public struct ButtonAppearance');
  const fields = firstGroups(appearance, /^ {2}public let (\w+: \S+)$/gm);
  assert.deepEqual(fields.slice(0, 6), [
    'backgroundColor: AppColorRole?',
    'textColor: AppColorRole',
    'borderColor: AppColorRole?',
    'spinnerColor: AppColorRole?',
    'borderWidth: Double?',
    'typography: AppTextStyle',
  ]);
  assert.equal(fields.at(-1), 'focusRing: FocusRingTokens?');
  assert.match(kotlin, /\n {4}val focusRing: FocusRingTokens\?,\n/);
});

test('the icon slot: two non-optional dimensions, 18 / 6 at compact and 20 / 8 elsewhere', () => {
  const appearance = block(swift, 'nonisolated public struct ButtonAppearance');
  assert.match(appearance, /\n {2}public let iconSize: Double\n {2}public let iconGap: Double\n/);
  assert.match(kotlin, /\n {4}val iconSize: Double,\n {4}val iconGap: Double,\n/);
  const sizes = firstGroups(repoSwift(), /^ {10}iconSize: ([\d.]+),$/gm);
  assert.equal(sizes.length, 500, 'one slot per look');
  assert.deepEqual([...new Set(sizes)].sort(), ['18.0', '20.0']);
  assert.match(repoKotlin(), /\n {36}iconSize = 18\.0,\n {36}iconGap = 6\.0,\n/);
});

test('ButtonSpec: one instance per context, the lookup returns none for a disallowed one', () => {
  const spec = block(swift, 'nonisolated public struct ButtonSpec');
  assert.match(spec, /\n {2}public let looks: \[ButtonLook\]\n/);
  assert.deepEqual(firstGroups(spec, /^ {2}public static let (\w+) = ButtonSpec\(/gm), CONTEXT_IDS);
  const find = [
    '  public func appearance(variant: ButtonVariant, size: ButtonSize, state: ButtonState) -> ButtonAppearance? {',
    '    looks.first { $0.variant == variant && $0.size == size && $0.state == state }?.appearance',
    '  }',
  ];
  assert.ok(spec.includes(find.join('\n')), 'the Swift lookup');
  const ktFind = [
    '    fun appearance(',
    '        variant: ButtonVariant,',
    '        size: ButtonSize,',
    '        state: ButtonState,',
    '    ): ButtonAppearance? =',
    '        looks.firstOrNull { it.variant == variant && it.size == size && it.state == state }?.appearance',
  ];
  assert.ok(kotlin.includes(ktFind.join('\n')), 'the Kotlin lookup');
  assert.equal(firstGroups(spec, /ButtonLook\(/g).length, 14 * CONTEXT_IDS.length);
});

test('a look spells its combination as cases and its absent values as nil / null', () => {
  const light = block(swift, 'public static let light = ButtonSpec(');
  const first = [
    '      ButtonLook(',
    '        variant: .primary,',
    '        size: .large,',
    '        state: .enabled,',
    '        appearance: ButtonAppearance(',
    '          backgroundColor: .primary,',
    '          textColor: .onPrimary,',
    '          borderColor: nil,',
  ];
  assert.ok(light.includes(first.join('\n')), 'the first Swift look');
  const ktFirst = [
    '                looks =',
    '                    listOf(',
    '                        ButtonLook(',
    '                            variant = ButtonVariant.PRIMARY,',
  ];
  assert.ok(kotlin.includes(ktFirst.join('\n')), 'a list item starts where it stands');
  assert.match(kotlin, /\n {36}borderColor = null,\n/);
  assert.match(swift, /\n {10}focusRing: FocusRingTokens\.hcDark\n/);
});

test('the gallery: per contract its label and its entries with their test-ID constants', () => {
  const gallery = block(swift, 'nonisolated public enum ComponentGallery');
  assert.match(gallery, /\n {2}public static let buttonLabel: String = "Fixture label"\n/);
  assert.match(gallery, /\n {2}public static let button: \[ButtonGalleryEntry\] = \[\n/);
  assert.match(gallery, /testId: ButtonTestId\.primaryLargeEnabled\)/);
  assert.equal(firstGroups(gallery, /ButtonGalleryEntry\(/g).length, 14);
  assert.match(kotlin, /\n {4}val button: List<ButtonGalleryEntry> =\n {8}listOf\(\n/);
});

test('GalleryComponent: a case per contract with its id, the board-prefixed title and slug', () => {
  const sections = [
    'nonisolated public enum GalleryComponent: String, CaseIterable, Sendable {',
    '  case button',
    '',
    '  /// The section title: the board and the contract `gallery.title`.',
    '  public var title: String {',
    '    switch self {',
    '    case .button: "C01 Fixture buttons"',
    '    }',
    '  }',
    '',
    '  /// The kebab-case title: the section id is `ds-gallery-section-<slug>`.',
    '  public var slug: String {',
    '    switch self {',
    '    case .button: "c01-fixture-buttons"',
    '    }',
    '  }',
    '}',
  ];
  assert.equal(block(swift, 'nonisolated public enum GalleryComponent'), sections.join('\n'));
  const ktSections = [
    'enum class GalleryComponent(',
    '    val id: String,',
    '    val title: String,',
    '    val slug: String,',
    ') {',
    '    BUTTON("button", "C01 Fixture buttons", "c01-fixture-buttons"),',
    '}',
  ];
  assert.equal(block(kotlin, 'enum class GalleryComponent('), ktSections.join('\n'));
  for (const text of [swift, kotlin]) {
    assert.ok(text.indexOf('GalleryComponent') < text.indexOf('ComponentGallery'), 'before');
  }
});

test('Swift: every generated type is nonisolated and public', () => {
  for (const text of [swift, repoSwift()]) {
    for (const line of text.split('\n').filter((l) => /\b(enum|struct) \w/.test(l))) {
      assert.match(line, /^ *nonisolated public (enum|struct) /, line);
    }
  }
});

test('layout: no line over 120 columns, no tab, no trailing space, even indents', () => {
  const files = { swift, kotlin, repoSwift: repoSwift(), repoKotlin: repoKotlin() };
  for (const [name, text] of Object.entries(files)) {
    const unit = name.toLowerCase().includes('kotlin') ? 4 : 2;
    text.split('\n').forEach((line, i) => {
      const at = `${name}:${i + 1}`;
      assert.ok(line.length <= 120, `${at} is ${line.length} columns`);
      assert.ok(!/\t| $/.test(line), `${at} has a tab or a trailing space`);
      assert.equal(/^ */.exec(line)[0].length % unit, 0, `${at} indent`);
    });
  }
});
