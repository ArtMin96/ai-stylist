  const name = block(swift, 'nonisolated public enum AppIconName');
  const cases = ['back', 'info', 'heart', 'heartFilled', 'wave', 'plus'];
  assert.deepEqual(firstGroups(name, /^ {2}case (\w+)/gm), cases);
